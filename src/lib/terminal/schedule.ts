/*
 * Engine stage E9 (docs/curriculum/LNX0_TERMINAL_CAPABILITY.md §17): cron (Debian's Vixie cron), flock, the time zone and
 * systemd-analyze calendar. The clock never moves, so nothing runs by itself: crontab installs and lists the per-user
 * crontab (/var/spool/cron/crontabs/USER), cron-next (a teaching helper, not a real command) computes the next run times
 * from the machine's fixed now and time zone, and cron-run (another teaching helper) runs the jobs that would be due next,
 * the way cron runs them (as their user, from the home folder, with cron's small environment, output mailed or discarded),
 * while the clock stays where it is. systemd timers are in services.ts.
 */

export const SPOOL = '/var/spool/cron/crontabs';
const CRON_PATH = '/usr/bin:/bin';

/** One job of a crontab: where it is, its schedule as written and parsed, the user it runs as and its command. */
export interface CronJob { source: string; line: number; user: string; when: string; spec: CronSpec; command: string; env: Readonly<Record<string, string>> }
/**
 * A crontab's text (a user's, or /etc/crontab and /etc/cron.d/* with a user field): its jobs, its environment lines and
 * Debian cron's errors (bad minute, bad hour, bad day-of-month, bad month, bad day-of-week, bad command, bad username,
 * premature EOF for a last line without a newline).
 */
export function parseCrontab(text: string, source: string, owner: string | null, known?: (user: string) => boolean): { jobs: CronJob[]; errors: { line: number; message: string }[] } {
  const jobs: CronJob[] = [], errors: { line: number; message: string }[] = [], env: Record<string, string> = {};
  const lines = text.split('\n');
  if (text && !text.endsWith('\n')) errors.push({ line: lines.length, message: 'premature EOF' });
  lines.forEach((raw, i) => {
    const line = raw.trim(), at = i + 1;
    if (!line || line.startsWith('#')) return;
    const assign = /^([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)$/.exec(line);
    if (assign && !/^[\d*@]/.test(line)) { env[assign[1]] = assign[2].replace(/^(["'])(.*)\1$/, '$2'); return; }
    const words = line.split(/\s+/), timeWords = words[0].startsWith('@') ? 1 : 5;
    const spec = parseCron(words.slice(0, timeWords));
    if ('error' in spec) { errors.push({ line: at, message: spec.error }); return; }
    let rest = line;
    for (let k = 0; k < timeWords; k++) rest = rest.replace(/^\S+\s*/, '');
    let user = owner ?? '';
    if (owner === null) {
      const m = /^(\S+)\s*/.exec(rest);
      // Fix (E19 batch): a system crontab line without a user field takes the command's first word as the user; cron's
      // getpwnam() then fails, the line is an error (cron logs it) and nothing runs.
      if (!m || !/^[a-z_][a-z0-9_-]*$/.test(m[1]) || (known && !known(m[1]))) { errors.push({ line: at, message: 'bad username' }); return; }
      user = m[1];
      rest = rest.slice(m[0].length);
    }
    if (!rest.trim()) { errors.push({ line: at, message: 'bad command' }); return; }
    jobs.push({ source, line: at, user, when: words.slice(0, timeWords).join(' '), spec, command: rest, env: { ...env } });
  });
  return { jobs, errors };
}

const HEADER = (file: string, now: string) => `# DO NOT EDIT THIS FILE - edit the master and reinstall.\n# (${file} installed on ${now})\n# (Cron version -- $Id: crontab.c,v 2.13 1994/01/17 03:20:37 vixie Exp $)\n`;
/** A crontab as `crontab -l` prints it (without the three header lines crontab wrote). */
const withoutHeader = (text: string) => text.startsWith('# DO NOT EDIT THIS FILE') ? text.split('\n').slice(3).join('\n') : text;
const fileText = (state: FsState, path: string) => { const n = state.nodes.get(physicalPath(state.nodes, path, true)); return n?.kind === 'file' ? n.content ?? '' : undefined; };

/** Every job of the machine: users' crontabs, /etc/crontab and /etc/cron.d/* (what cron reads; `readable` limits it to what a user may read). */
export function allJobs(state: FsState, readable?: string): CronJob[] {
  const jobs: CronJob[] = [], acc = accountsOf(state);
  const spool = state.nodes.get(physicalPath(state.nodes, SPOOL, true));
  if (spool?.kind === 'dir') for (const p of childrenOf(state.nodes, physicalPath(state.nodes, SPOOL, true))) {
    const user = baseName(p), text = fileText(state, p);
    if (text === undefined || !findUser(acc, user) || (readable && readable !== 'root' && readable !== user)) continue;
    jobs.push(...parseCrontab(withoutHeader(text), `crontab (${user})`, user).jobs);
  }
  const system = (path: string) => {
    const text = fileText(state, path), node = state.nodes.get(physicalPath(state.nodes, path, true));
    if (text === undefined || (readable && readable !== 'root' && node && !(node.mode & 0o004))) return;
    jobs.push(...parseCrontab(text, path, null, name => !!findUser(acc, name)).jobs);
  };
  systemCrontabs(state).forEach(system);
  return jobs;
}
/** /etc/crontab and the files of /etc/cron.d cron reads (names of letters, digits, _ and - only). */
function systemCrontabs(state: FsState): string[] {
  const out = ['/etc/crontab'], crond = physicalPath(state.nodes, '/etc/cron.d', true);
  if (state.nodes.get(crond)?.kind === 'dir') for (const p of childrenOf(state.nodes, crond)) if (/^[A-Za-z0-9_-]+$/.test(baseName(p))) out.push(p);
  return out;
}
/** Fix (E19 batch): the lines of the system crontabs cron rejects for a user that does not exist (it logs them when it reads the files). */
export function badUserLines(state: FsState): { path: string; line: number }[] {
  const acc = accountsOf(state);
  return systemCrontabs(state).flatMap(path => {
    const text = fileText(state, path);
    if (text === undefined) return [];
    return parseCrontab(text, path, null, name => !!findUser(acc, name)).errors.filter(e => e.message === 'bad username').map(e => ({ path, line: e.line }));
  });
}

/** What the scheduling commands write, as whom they run, and how flock runs its command. */
export interface ScheduleIo {
  out(data: string): void; err(line: string): void; user: string; tty: boolean; profile: ShellProfile;
  argv(state: FsState, argv: string[]): { state: FsState; status: number };
  text(state: FsState, source: string, opts: { env?: Record<string, string> }): { state: FsState; status: number };
}
type Result = { state: FsState; status: number };

export function scheduleCommand(cmd: string, state: FsState, args: readonly string[], io: ScheduleIo): Result {
  const say = (l: string) => io.out(`${l}\n`);
  switch (cmd) {
    case 'crontab': return crontab(state, args, io);
    case 'cron-next': return cronNext(state, args, io, say);
    case 'cron-run': return cronRun(state, args, io, say);
    case 'flock': return flock(state, args, io);
    case 'timedatectl': return timedatectl(state, args, io, say);
    default: return analyze(state, args, io, say);
  }
}

const CRONTAB_USAGE = ['usage:\tcrontab [-u user] file', '\tcrontab [ -u user ] [ -i ] { -e | -l | -r }', '\t\t(default operation is replace, per 1003.2)',
  "\t-e\t(edit user's crontab)", "\t-l\t(list user's crontab)", "\t-r\t(delete user's crontab)", "\t-i\t(prompt before deleting user's crontab)"];

function crontab(state: FsState, args: readonly string[], io: ScheduleIo): Result {
  const o = getopt(args, 'u:lrei', {});
  if ('error' in o) { io.err(`crontab: ${o.error}`); CRONTAB_USAGE.forEach(l => io.err(l)); return { state, status: 1 }; }
  const user = o.flags.get('u')?.at(-1) ?? io.user, acc = accountsOf(state);
  if (user !== io.user && io.user !== 'root') { io.err('must be privileged to use -u'); return { state, status: 1 }; }
  if (!findUser(acc, user)) { io.err(`crontab: user '${user}' unknown`); return { state, status: 1 }; }
  const path = `${SPOOL}/${user}`, current = fileText(state, path);
  if (o.flags.has('e')) { io.err('crontab: 模擬環境沒有文字編輯器：請把內容寫進檔案，再用 crontab 檔案 安裝（例如 crontab mycron）'); return { state, status: 1 }; }
  if (o.flags.has('l')) {
    if (current === undefined) { io.err(`no crontab for ${user}`); return { state, status: 1 }; }
    io.out(withoutHeader(current));
    return { state, status: 0 };
  }
  if (o.flags.has('r')) {
    if (current === undefined) { io.err(`no crontab for ${user}`); return { state, status: 1 }; }
    const nodes = new Map(state.nodes);
    nodes.delete(physicalPath(nodes, path, true));
    return { state: { ...state, nodes }, status: 0 };
  }
  if (o.operands.length !== 1) { CRONTAB_USAGE.forEach(l => io.err(l)); return { state, status: 1 }; }
  const file = o.operands[0], read = readPath(state, file);
  if ('error' in read) { io.err(`${file}: ${read.error === 'EACCES' ? 'Permission denied' : read.error === 'EISDIR' ? 'Is a directory' : 'No such file or directory'}`); return { state, status: 1 }; }
  const parsed = parseCrontab(read.text, file, user);
  if (parsed.errors.length) {
    parsed.errors.forEach(e => io.err(`"${file}":${e.line}: ${e.message}`));
    io.err("errors in crontab file, can't install.");
    return { state, status: 1 };
  }
  // Installed by the setgid crontab program: the spool folder exists (created if the machine lacks it), the file is the user's, mode 600, group crontab.
  const nodes = new Map(state.nodes);
  let at = '';
  for (const part of SPOOL.split('/').filter(Boolean)) { at += `/${part}`; if (!nodes.has(at)) nodes.set(at, { kind: 'dir', mode: at === SPOOL ? 0o730 : 0o755, owner: 'root', ...at === SPOOL && findGroup(acc, 'crontab') ? { group: 'crontab' } : {} }); }
  const group = findGroup(acc, 'crontab') ? 'crontab' : user, now = zoneStamp(zoneOf(state), clockOf(state).now);
  const node: FsNode = { kind: 'file', mode: 0o600, owner: user, ...group !== user ? { group } : {}, content: HEADER(file, now.replace(/^(\w{3}) (\d{4})-(\d\d)-(\d\d) (\S+) \S+$/, (_, d: string, y: string, mo: string, day: string, t: string) => `${d} ${['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'][Number(mo) - 1]} ${String(Number(day)).padStart(2)} ${t} ${y}`)) + read.text };
  nodes.set(path, node);
  return { state: { ...state, nodes }, status: 0 };
}

/** cron-next (a teaching helper): the next times of a schedule, or of every job of the machine (-l). */
function cronNext(state: FsState, args: readonly string[], io: ScheduleIo, say: (l: string) => void): Result {
  const o = getopt(args, 'n:l', {});
  if ('error' in o) { io.err(`cron-next: ${o.error}`); return { state, status: 1 }; }
  const count = Number(o.flags.get('n')?.at(-1) ?? 5), zone = zoneOf(state), now = clockOf(state).now;
  if (!Number.isInteger(count) || count < 1 || count > 50) { io.err('cron-next: -n 需要 1 到 50 的整數'); return { state, status: 1 }; }
  if (o.flags.has('l')) {
    const jobs = allJobs(state, io.user);
    if (!jobs.length) { say('（這台機器沒有任何排程工作）'); return { state, status: 0 }; }
    const rows = jobs.map(j => { const next = nextCron(j.spec, zone, now, 1)[0]; return { next, cells: [next !== undefined ? zoneStamp(zone, next) : j.spec.reboot ? '@reboot（開機時）' : '-', j.user, j.source, j.when, j.command] }; })
      .sort((a, b) => (a.next ?? Infinity) - (b.next ?? Infinity));
    const table = [['NEXT', 'USER', 'SOURCE', 'SCHEDULE', 'COMMAND'], ...rows.map(r => r.cells)];
    const widths = table[0].map((_, i) => Math.max(...table.map(r => r[i].length)));
    table.forEach(r => say(r.map((c, i) => i === r.length - 1 ? c : c.padEnd(widths[i])).join('  ')));
    if (jobs.some(j => j.env.CRON_TZ !== undefined)) say(`（注意：Debian／Ubuntu 的 cron 不支援 CRON_TZ，上面一律以系統時區 ${zone.name} 計算；RHEL 的 cronie 才支援 CRON_TZ）`);
    return { state, status: 0 };
  }
  if (o.operands.length !== 1) { io.err("用法：cron-next [-n 次數] '分 時 日 月 週' | cron-next -l（教學輔助，不是真實的指令）"); return { state, status: 1 }; }
  const spec = parseCron(o.operands[0].trim().split(/\s+/));
  if ('error' in spec) { io.err(`cron-next: ${spec.error}`); return { state, status: 1 }; }
  if (spec.reboot) { say('（@reboot：只在開機時執行；模擬環境不重新開機）'); return { state, status: 0 }; }
  const times = nextCron(spec, zone, now, count);
  if (!times.length) say('（十年內不會執行）');
  times.forEach(t => say(zoneStamp(zone, t)));
  return { state, status: 0 };
}

/**
 * cron-run (a teaching helper): runs the jobs due at the next run time the way cron would — as the job's user, in the home
 * folder, with SHELL=/bin/sh, PATH=/usr/bin:/bin and the crontab's variables, % in the command ending it (the rest is
 * standard input) — and handles their output like cron: mailed to MAILTO or the user when the machine has an MTA, else
 * discarded with a journal note. The machine's clock does not move.
 */
function cronRun(state: FsState, args: readonly string[], io: ScheduleIo, say: (l: string) => void): Result {
  if (args.length) { io.err('用法：cron-run（教學輔助，不是真實的指令；不接受參數）'); return { state, status: 1 }; }
  const zone = zoneOf(state), now = clockOf(state).now, jobs = allJobs(state);
  // Fix (E19 batch): cron reads the system crontabs first and logs the lines it rejects (Debian's message).
  let base = state;
  for (const b of badUserLines(state)) {
    const daemon = tableOf(base).find(p => commOf(p.command) === 'cron');
    base = journal(base, 'cron', daemon?.pid ?? 1, `Error: bad username; while reading ${b.path}`, 3);
  }
  state = base;
  const times = jobs.map(j => nextCron(j.spec, zone, now, 1)[0]).filter((t): t is number => t !== undefined);
  if (!times.length) { say('cron-run：這台機器沒有會到期的排程工作'); return { state, status: 1 }; }
  const due = Math.min(...times), batch = jobs.filter(j => nextCron(j.spec, zone, now, 1)[0] === due);
  say(`cron-run（教學輔助）：模擬 ${zoneStamp(zone, due)} 到期的 ${batch.length} 個工作；機器的時鐘不前進`);
  let next = state;
  for (const job of batch) {
    const acc = accountsOf(next), u = findUser(acc, job.user);
    say(`[${job.user}] ${job.command}`);
    if (!u) { say(`  cron 找不到使用者 ${job.user}，不執行`); continue; }
    // % ends the command; the rest (each further % a new line) is its standard input; \% is a literal %.
    const pieces = job.command.split(/(?<!\\)%/).map(p => p.replace(/\\%/g, '%'));
    const command = pieces[0], stdin = pieces.length > 1 ? `${pieces.slice(1).join('\n')}\n` : null;
    const env: Record<string, string> = { SHELL: '/bin/sh', PATH: CRON_PATH, HOME: u.home, LOGNAME: job.user, USER: job.user, ...job.env };
    const pid = nextPid(next);
    next = journal({ ...next, lastPid: pid }, 'CRON', pid, `(${job.user}) CMD (${command})`);
    const r = asUser(next, job.user, undefined, s => runText(s, command, io.profile, { name: '/bin/sh', env, stdin }));
    next = r.state;
    const output = r.events.map(e => e.data).join(''), lines = output ? output.replace(/\n$/, '').split('\n').length : 0;
    const mailto = job.env.MAILTO ?? job.user;
    let where: string;
    if (!output) where = '沒有輸出';
    else if (mailto === '') where = `輸出 ${lines} 行：MAILTO="" 不寄送，輸出被捨棄`;
    else if (next.schedule?.mta) {
      const box = `/var/mail/${mailto}`, nodes = new Map(next.nodes), old = nodes.get(box);
      const mail = `From: root (Cron Daemon)\nTo: ${mailto}\nSubject: Cron <${job.user}@${next.host ?? 'logic-island'}> ${command}\n\n${output.endsWith('\n') ? output : `${output}\n`}\n`;
      if (!nodes.has('/var/mail')) nodes.set('/var/mail', { kind: 'dir', mode: 0o2775 & 0o777, owner: 'root', ...findGroup(accountsOf(next), 'mail') ? { group: 'mail' } : {} });
      nodes.set(box, old?.kind === 'file' ? { ...old, content: (old.content ?? '') + mail } : { kind: 'file', mode: 0o660, owner: mailto, ...findGroup(accountsOf(next), 'mail') ? { group: 'mail' } : {}, content: mail });
      next = { ...next, nodes };
      where = `輸出 ${lines} 行：寄到 ${box}`;
    } else {
      next = journal(next, 'CRON', pid, '(CRON) info (No MTA installed, discarding output)');
      where = `輸出 ${lines} 行：沒有安裝郵件伺服器（MTA），cron 捨棄了輸出`;
    }
    say(`  結束碼 ${r.status}；${where}`);
  }
  return { state: next, status: 0 };
}
function journal(state: FsState, id: string, pid: number, message: string, priority = 6): FsState {
  if (!state.journal) return state;
  return { ...state, journal: [...state.journal, { time: clockOf(state).now, unit: 'cron.service', id, pid, priority, message }].slice(-MAX_JOURNAL) };
}

/**
 * flock [-n] [-w s] [-E code] [-c command] lockfile [command…]: a lock is held by a process of the table that lists the
 * file in its locks (lesson data: a long backup still running). Taken: -n (and -w, since time never passes) give up at
 * once with status 1; without them flock would wait forever, which the simulation says. Free: the lock file is created
 * if needed and the command runs.
 */
function flock(state: FsState, args: readonly string[], io: ScheduleIo): Result {
  const usage = (line: string): Result => { io.err(`flock: ${line}`); io.err("Try 'flock --help' for more information."); return { state, status: 64 }; };
  let i = 0, nonblock = false, wait: string | undefined, conflict: string | undefined, command: string | undefined;
  for (; i < args.length; i++) {
    const a = args[i];
    if (a === '--') { i++; break; }
    if (!a.startsWith('-') || a === '-') break;
    if (a === '-n' || a === '--nonblock' || a === '--nb') nonblock = true;
    else if (a === '-w' || a === '--wait' || a === '--timeout') wait = args[++i];
    else if (a === '-E' || a === '--conflict-exit-code') conflict = args[++i];
    else if (a === '-c' || a === '--command') command = args[++i];
    else if (/^-[nsxo]+$/.test(a) || ['--shared', '--exclusive', '--close'].includes(a)) nonblock ||= a.includes('n') && !a.startsWith('--');
    else return usage(a.startsWith('--') ? `unrecognized option '${a}'` : `invalid option -- '${a[1]}'`);
  }
  const lockfile = args[i];
  let rest = args.slice(i + 1);
  if (rest[0] === '-c' || rest[0] === '--command') { command = rest[1]; rest = []; }
  if (!lockfile) return usage('not enough arguments');
  if (/^\d+$/.test(lockfile) && command === undefined && !rest.length) { io.err('flock: 模擬環境不支援以檔案描述子加鎖（flock -n 9）；請寫成 flock -n 鎖檔 指令'); return { state, status: 1 }; }
  if (command === undefined && !rest.length) { io.err('flock: 模擬環境：請在鎖檔之後寫出要執行的指令（或用 -c）'); return { state, status: 1 }; }
  const path = physicalPath(state.nodes, resolvePath(state, lockfile), true);
  const holder = tableOf(state).find(p => p.locks?.includes(path));
  if (holder) {
    if (nonblock || wait !== undefined) return { state, status: Number(conflict ?? 1) };
    io.err(`flock: 模擬環境：${lockfile} 的鎖被 PID ${holder.pid}（${commOf(holder.command)}）持有，flock 會一直等下去；請用 -n（拿不到鎖就放棄）或 -w 秒數`);
    return { state, status: 1 };
  }
  let next = state;
  if (!walkExists(state, path)) {
    const nodes = new Map(state.nodes), opened = openWrite(nodes, state, lockfile, true);
    if ('error' in opened) { io.err(`flock: cannot open lock file ${lockfile}: ${opened.error === 'EACCES' ? 'Permission denied' : opened.error === 'ENOENT' ? 'No such file or directory' : opened.error}`); return { state, status: 66 }; }
    next = { ...state, nodes };
  }
  return command !== undefined ? io.text(next, command, {}) : io.argv(next, rest);
}
const walkExists = (state: FsState, path: string) => { const w = walk(state, path); return !('error' in w) && !!w.node; };

function timedatectl(state: FsState, args: readonly string[], io: ScheduleIo, say: (l: string) => void): Result {
  const [verb = 'status'] = args, zone = zoneOf(state), now = clockOf(state).now;
  const label = (l: string) => `${l}:`.padStart(26);
  switch (verb) {
    case 'status': {
      const { offset, abbr } = offsetAt(zone, now);
      say(`${label('Local time')} ${zoneStamp(zone, now)}`);
      say(`${label('Universal time')} ${zoneStamp(UTC_ZONE, now)}`);
      say(`${label('RTC time')} ${zoneStamp(UTC_ZONE, now).replace(/ UTC$/, '')}`);
      say(`${label('Time zone')} ${zone.name} (${abbr}, ${offsetText(offset)})`);
      say(`${label('System clock synchronized')} yes`);
      say(`${label('NTP service')} active`);
      say(`${label('RTC in local TZ')} no`);
      return { state, status: 0 };
    }
    case 'show':
      say(`Timezone=${zone.name}`); say('LocalRTC=no'); say('CanNTP=yes'); say('NTP=yes'); say('NTPSynchronized=yes');
      return { state, status: 0 };
    case 'list-timezones': ZONES.filter(z => z.name !== 'Etc/UTC').map(z => z.name).sort().forEach(say); return { state, status: 0 };
    case 'set-timezone': case 'set-time': case 'set-ntp': case 'set-local-rtc':
      io.err(`timedatectl ${verb}：模擬環境的時間與時區由課程設定，只能查看（真實系統：sudo timedatectl set-timezone Asia/Taipei）`);
      return { state, status: 1 };
    default: io.err(`Unknown command verb '${verb}'.`); return { state, status: 1 };
  }
}

/** systemd-analyze calendar [--iterations=N] EXPRESSION…: the normalized form and the next elapses, in the machine's zone. */
function analyze(state: FsState, args: readonly string[], io: ScheduleIo, say: (l: string) => void): Result {
  const [verb, ...rest] = args;
  if (verb !== 'calendar') { io.err(`systemd-analyze：模擬環境只支援 systemd-analyze calendar 運算式${verb ? `（${verb} 不支援）` : ''}`); return { state, status: 1 }; }
  let iterations = 1;
  const exprs: string[] = [];
  for (let i = 0; i < rest.length; i++) {
    const a = rest[i], m = /^--iterations(?:=(.*))?$/.exec(a);
    if (m) { const v = m[1] ?? rest[++i]; if (!/^\d+$/.test(v ?? '') || Number(v) < 1) { io.err(`Failed to parse iterations: ${v ?? ''}`); return { state, status: 1 }; } iterations = Math.min(Number(v), 50); continue; }
    exprs.push(a);
  }
  if (!exprs.length) { io.err('Too few arguments.'); return { state, status: 1 }; }
  const zone = zoneOf(state), now = clockOf(state).now, label = (l: string) => `${l}:`.padStart(16);
  let status = 0;
  exprs.forEach((expr, k) => {
    const spec = parseCalendar(expr);
    if (!spec) { io.err(`Failed to parse calendar specification '${expr}': Invalid argument`); status = 1; return; }
    if (k) say('');
    say(`${label('Original form')} ${expr}`);
    say(`${label('Normalized form')} ${normalizeCalendar(spec)}`);
    const times = nextCalendar(spec, zone, now, iterations);
    if (!times.length) { say(`${label('Next elapse')} never`); return; }
    times.forEach((t, i) => {
      say(`${label(i ? `Iteration #${i + 1}` : 'Next elapse')} ${zoneStamp(zone, t)}`);
      if (zone.offset !== 0 || zone.dst) say(`${label('(in UTC)')} ${zoneStamp(UTC_ZONE, t)}`);
      say(`${label('From now')} ${relativeText(t - now).replace(/ ago$/, ' left')}`);
    });
  });
  return { state, status };
}
