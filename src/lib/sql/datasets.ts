/** Rows from fixed arithmetic (multipliers coprime to the sizes), so every customer and product occurs. */
function salesRows(customers: number, products: number, orders: number, k: { c: number; p: number; day: number; start: string }) {
  return `
WITH RECURSIVE n(i) AS (SELECT 1 UNION ALL SELECT i + 1 FROM n WHERE i < ${customers})
INSERT INTO customers SELECT i, '顧客' || printf('%04d', i),
  CASE i % 6 WHEN 0 THEN '台北' WHEN 1 THEN '新北' WHEN 2 THEN '台中' WHEN 3 THEN '台南' WHEN 4 THEN '高雄' ELSE '新竹' END,
  date('2023-01-01', '+' || (i * 7 % 900) || ' days') FROM n;
WITH RECURSIVE n(i) AS (SELECT 1 UNION ALL SELECT i + 1 FROM n WHERE i < ${products})
INSERT INTO products SELECT i, '商品' || printf('%03d', i),
  CASE i % 5 WHEN 0 THEN '周邊' WHEN 1 THEN '配件' WHEN 2 THEN '顯示器' WHEN 3 THEN '音訊' ELSE '儲存' END,
  100 + (i * 37 % 50) * 50 FROM n;
WITH RECURSIVE n(i) AS (SELECT 1 UNION ALL SELECT i + 1 FROM n WHERE i < ${orders})
INSERT INTO orders SELECT i, (i * ${k.c}) % ${customers} + 1, (i * ${k.p}) % ${products} + 1, i % 5 + 1,
  CASE WHEN i % 20 = 0 THEN 'cancelled' WHEN i % 7 = 0 THEN 'pending' ELSE 'shipped' END,
  date('${k.start}', '+' || (i * ${k.day} % 640) || ' days') FROM n;`;
}

