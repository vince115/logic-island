type DocRow = [id: number, customer: [number, string, string], items: [string, number, number][], status: string, on: string];
/** The INSERT for order documents. Called once per dataset and marked pure (see `sales`): pages that never read DATASETS must not carry it. */
function docRows(rows: DocRow[]): string {
  return `INSERT INTO orders_doc VALUES\n${rows.map(([id, customer, items, status, on]) =>
    `  (${id}, '${JSON.stringify({ customer: { id: customer[0], name: customer[1], city: customer[2] }, items: items.map(([product, qty, price]) => ({ product, qty, price })), status, ordered_on: on })}')`).join(',\n')};`;
}

