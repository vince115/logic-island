/*
 * Phase F.1a teaching datasets for the SQL playground (DB01–DB05; Phase F.1b adds `company` for DB06 and `empty` for
 * the DDL lessons). Each is a script run on an empty in-memory SQLite
 * database, so resetting always gives the same rows. The `-b` variants have the same tables with other rows: exercises
 * are also checked on them, so a query that only fits the visible data (a hard-coded id, a missing condition) fails.
 * Edge cases are there on purpose: NULL emails and scores, a student and a course with no enrollment, a customer with
 * no order, a product never ordered, and a self-reference (customers.referred_by). `company` (F.1b) has salary ties
 * inside a department, a department with no employee, and a manager hierarchy (employees.manager_id, NULL at the top)
 * four levels deep. `empty` has no table: the learner creates them (DB07, DB09). `registrar` (DB10) is one
 * unnormalized table of course records, with an update anomaly already in it (one major with two offices);
 * `registrar-b` has others (two majors with two offices each, one course title spelled two ways). `sales` (F.1c, DB11–DB12)
 * is large enough for query plans and timings to matter (2,000 customers, 200 products, 30,000 orders), generated by a
 * recursive CTE from fixed arithmetic, so it is the same on every run; it has no index besides the primary keys.
 * `auth` (F.1d, DB16–DB17): user accounts with password hashes (made-up values, never real ones), roles and an inactive
 * account, for parameterized and injected login queries. `documents` (DB18): order documents as JSON text (queried
 * with SQLite's JSON functions), a key-value table and a follower graph, so the NoSQL models can be tried in SQL.
 */

