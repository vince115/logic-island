/*
 * WEB12 Browser storage: localStorage and cookies (WEB-4). A web-code lesson on the made-up 小島圖書館: why a page
 * stores data in the browser and the limits of doing so, localStorage (strings only, null when missing, JSON with a
 * fallback for broken text), sessionStorage (one tab), cookies (sent with every request; document.cookie writes one
 * cookie at a time; max-age; HttpOnly, Secure, SameSite), versioned data with a migration on load, and what must not
 * be kept in the browser. The preview's storage is the frame's in-memory stand-in (engine stage W4): `setup.storage`
 * and `setup.cookies` are what an earlier visit left, and a returning visitor is a variant. Where the stand-in differs
 * from a browser the text says what a browser does: pressing 執行 keeps localStorage and cookies but starts with an
 * empty sessionStorage (a new tab, not a reload); property access (`localStorage.theme`) is not supported; a cookie's
 * expiry, path, Secure and SameSite are not modelled, and no check can read them (a script cannot either).
 * Every `observe` fact and every exercise (solution, starter, mistakes, variants) is run in Chromium by the tests.
 * Out of scope: IndexedDB and the Cache API (named once), service workers (MOB09), authentication flows, the law.
 */

