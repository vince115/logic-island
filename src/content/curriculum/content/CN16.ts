/** RFC 6455 §5.7: a masked text frame from a client carrying "Hello", masking key 37 fa 21 3d. */
const TRACE_FRAME = [0x81, 0x85, 0x37, 0xfa, 0x21, 0x3d, 0x7f, 0x9f, 0x4d, 0x51, 0x58];
const hex2 = (b: number) => b.toString(16).padStart(2, '0');
const bits = (b: number) => b.toString(2).padStart(8, '0').replace(/^(.{4})/, '$1 ');

/** Runs the traced decoder on TRACE_FRAME and records the variables (as Python prints them) after each shown line. */
function decodeSteps(): TraceStep[] {
  const f = TRACE_FRAME;
  const steps: TraceStep[] = [];
  const vars: Record<string, string> = {};
  const snap = (line: number, note: string, marks: { at: number; kind: Mark }[] = [], extra: { pointers?: Record<string, number>; range?: { from: number; to: number; label: string } } = {}, output?: string) =>
    steps.push({ line, note, vars: { ...vars }, arrays: [{ name: 'frame（十六進位）', cells: f.map(hex2), marks, ...extra }], ...(output ? { output } : {}) });

  vars.frame = code`b'\x81\x857\xfa!=\x7f\x9fMQX'`;
  snap(1, '`bytes.fromhex` 把 11 個十六進位位元組變成 bytes。Python 顯示 bytes 時，可列印的位元組直接寫成字元：0x37 是 7、0x21 是 !、0x3d 是 =、0x4d 0x51 0x58 是 MQX，所以 repr 看起來很亂；下方的格子才是真正的位元組。這是 RFC 6455 的例子：客戶端送出、內容為 Hello 的文字訊框。');
  const fin = f[0] >> 7;
  vars.fin = String(fin);
  snap(2, `第 0 個位元組 0x${hex2(f[0])} 的二進位是 ${bits(f[0])}。右移 7 位只留下最高位元：FIN = ${fin}，表示這是訊息的最後一個訊框（本例也是唯一的一個）。`, [{ at: 0, kind: 'read' }]);
  const opcode = f[0] & 0x0f;
  vars.opcode = String(opcode);
  snap(3, `和 0x0F 做 AND 只留下低 4 位元：opcode = ${opcode}，文字訊框。中間的 3 個位元是 RSV1～RSV3，沒有協商擴充時都必須是 0。`, [{ at: 0, kind: 'read' }]);
  const masked = f[1] >> 7;
  vars.masked = String(masked);
  snap(4, `第 1 個位元組 0x${hex2(f[1])} 的二進位是 ${bits(f[1])}。最高位元是 MASK = ${masked}：客戶端送給伺服器的訊框一定要遮罩，伺服器看到 0 就要關閉連線。`, [{ at: 1, kind: 'read' }]);
  const length = f[1] & 0x7f;
  vars.length = String(length);
  snap(5, `低 7 位元是長度：0x${hex2(f[1])} & 0x7F = ${length}。0～125 直接就是本文的位元組數；126 與 127 表示真正的長度在後面的 2 或 8 個位元組。`, [{ at: 1, kind: 'read' }]);
  let i = 2;
  vars.i = String(i);
  snap(6, 'i 指向標頭之後的下一個位元組：第 2 個。', [], { pointers: { i } });
  snap(7, `length 是 ${length}，不是 126，跳過讀取 16 位元延伸長度的兩行；若是 126，就把第 2、3 個位元組以大端序讀成長度，i 改成 4。`, [], { pointers: { i } });
  const key = f.slice(i, i + 4);
  vars.key = code`b'7\xfa!='`;
  snap(10, `取出 4 個位元組的遮罩金鑰 ${key.map(hex2).join(' ')}（Python 顯示成 b'7\\xfa!='）。金鑰就放在訊框裡，任何人都讀得到，所以遮罩不是加密。`, [0, 1, 2, 3].map(k => ({ at: i + k, kind: 'read' as Mark })), { pointers: { i }, range: { from: i, to: i + 3, label: '遮罩金鑰' } });
  i += 4;
  vars.i = String(i);
  snap(11, `i 跳過金鑰，指向本文的第一個位元組：第 ${i} 個。本文從這裡到結尾共 ${length} 個位元組。`, [], { pointers: { i }, range: { from: i, to: i + length - 1, label: '遮罩後的本文' } });
  const payload: number[] = [];
  vars.payload = "bytearray(b'')";
  snap(12, 'payload 是可變的 bytearray，用來放還原後的位元組。', [], { pointers: { i }, range: { from: i, to: i + length - 1, label: '遮罩後的本文' } });
  for (let j = 0; j < length; j++) {
    const b = f[i + j] ^ key[j % 4];
    payload.push(b);
    vars.j = String(j);
    vars.payload = `bytearray(b'${String.fromCharCode(...payload)}')`;
    snap(14, `j = ${j}：本文第 ${j} 個位元組 0x${hex2(f[i + j])} 和金鑰第 ${j} % 4 = ${j % 4} 個位元組 0x${hex2(key[j % 4])} 做 XOR，得到 0x${hex2(b)}，也就是 '${String.fromCharCode(b)}'。${j === 4 ? '金鑰只有 4 個位元組，所以第 4 個位元組又回到金鑰的第 0 個。' : ''}`,
      [{ at: i + j, kind: 'read' }, { at: 2 + (j % 4), kind: 'read' }], { pointers: { i, 'i + j': i + j }, range: { from: i, to: i + length - 1, label: '遮罩後的本文' } });
  }
  const text = String.fromCharCode(...payload);
  snap(15, `5 個位元組都還原了，以 ASCII 解碼得到 ${text}。同樣的 XOR 再做一次就會變回遮罩後的位元組，所以客戶端遮罩、伺服器還原用的是同一段程式。`, [], {}, `fin=${fin} opcode=${opcode} masked=${masked} text=${text}`);
  return steps;
}

