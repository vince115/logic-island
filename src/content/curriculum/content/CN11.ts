// ---- the receive-buffer trace ---------------------------------------------------------------------------------------
const FRAMING_PY = code`chunks = [b"\x00\x00\x00", b"\x02hi\x00\x00\x00\x02", b"ok\x00\x00\x00\x03bye"]
buf = bytearray()
for chunk in chunks:
    buf += chunk
    while len(buf) >= 4:
        n = int.from_bytes(buf[:4], "big")
        if len(buf) < 4 + n:
            break
        msg = buf[4:4 + n].decode("utf-8")
        del buf[:4 + n]
        print(msg)`;

/** The bytes each of the three recv calls returns in the traced program (and in the framing example): 3, 7 and 9. */
const TRACE_CHUNKS = [[0x00, 0x00, 0x00], [0x02, 0x68, 0x69, 0x00, 0x00, 0x00, 0x02], [0x6f, 0x6b, 0x00, 0x00, 0x00, 0x03, 0x62, 0x79, 0x65]];
const hex2 = (b: number) => b.toString(16).padStart(2, '0');
const range = (from: number, to: number) => Array.from({ length: to - from }, (_, i) => from + i);

/** Runs the traced decoder on TRACE_CHUNKS and records the receive buffer (a queue of bytes) after each line. */
function framingSteps(): TraceStep[] {
  const steps: TraceStep[] = [];
  let buf: number[] = [];
  const output: string[] = [];
  const vars: Record<string, string> = {};
  const snap = (line: number, note: string, marks: { at: number; kind: Mark }[] = []) => steps.push({
    line, note, vars: { ...vars }, containers: [{ name: '接收緩衝區 buf', kind: 'queue', items: buf.map(hex2), marks }],
    ...(output.length ? { output: output.join('\n') } : {}),
  });
  vars.chunks = '3 段：3、7、9 個位元組';
  snap(1, '`chunks` 模擬三次 `recv` 各拿到的位元組。訊息是 hi、ok、bye 三個訊框，每個都是 4 位元組的長度加上內容，共 19 個位元組；網路把它切成 3、7、9 個位元組，切點和訊框的邊界無關。');
  vars['len(buf)'] = '0';
  snap(2, '`buf` 是接收緩衝區：收到但還沒切成訊息的位元組都放在這裡。新資料接在尾端，切出的訊框從前端移除，就像一個位元組的佇列。');
  TRACE_CHUNKS.forEach((chunk, i) => {
    vars.chunk = `${chunk.map(hex2).join(' ')}（${chunk.length} 個位元組）`;
    snap(3, `第 ${i + 1} 次 recv 拿到 ${chunk.length} 個位元組。`);
    const before = buf.length;
    buf = [...buf, ...chunk];
    vars['len(buf)'] = String(buf.length);
    snap(4, `把這 ${chunk.length} 個位元組接到緩衝區尾端，現在共有 ${buf.length} 個。`, range(before, buf.length).map(at => ({ at, kind: 'write' })));
    for (;;) {
      if (buf.length < 4) {
        snap(5, buf.length ? `緩衝區只有 ${buf.length} 個位元組，不到 4 個：連長度都還不知道，離開 while，等下一次 recv。` : '緩衝區是空的，這一段的訊框都切完了，離開 while，等下一次 recv。');
        break;
      }
      snap(5, `緩衝區有 ${buf.length} 個位元組，至少 4 個：標頭到齊了，可以讀出長度。`);
      const n = buf[0] * 2 ** 24 + buf[1] * 2 ** 16 + buf[2] * 2 ** 8 + buf[3];
      vars.n = String(n);
      snap(6, `前 4 個位元組 ${buf.slice(0, 4).map(hex2).join(' ')} 以大端序（先到的是高位）讀成無號整數：n = ${n}。只讀不刪，標頭仍留在緩衝區。`, range(0, 4).map(at => ({ at, kind: 'read' })));
      if (buf.length < 4 + n) {
        snap(7, `這個訊框共需 4 + ${n} = ${4 + n} 個位元組，緩衝區只有 ${buf.length} 個：內容還沒到齊。`);
        snap(8, 'break：已到的標頭不能丟，留在緩衝區裡；下一次 recv 帶來其餘的內容時，從這裡重新讀一次長度。', range(0, buf.length).map(at => ({ at, kind: 'pending' })));
        break;
      }
      snap(7, `這個訊框共需 4 + ${n} = ${4 + n} 個位元組，緩衝區有 ${buf.length} 個：完整了。`);
      const msg = String.fromCharCode(...buf.slice(4, 4 + n));
      vars.msg = `'${msg}'`;
      snap(9, `取出標頭後面的 ${n} 個位元組（${buf.slice(4, 4 + n).map(hex2).join(' ')}），用 UTF-8 解碼成 '${msg}'。`, range(4, 4 + n).map(at => ({ at, kind: 'read' })));
      buf = buf.slice(4 + n);
      vars['len(buf)'] = String(buf.length);
      snap(10, `從前端刪掉這個訊框的 ${4 + n} 個位元組（標頭與內容），剩 ${buf.length} 個${buf.length ? '，它們是下一個訊框的開頭' : ''}。`);
      output.push(msg);
      snap(11, `印出 ${msg}，回到 while 檢查剩下的位元組夠不夠再切一個。`);
    }
  });
  snap(3, '三段資料都處理完，切出 hi、ok、bye 三則訊息，緩衝區是空的，沒有留下半個訊框。第二次 recv 剛好切在 ok 的標頭之後，第三次一次帶來兩個訊框，程式都照樣切對了。');
  return steps;
}

