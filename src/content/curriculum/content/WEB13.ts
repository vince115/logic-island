/*
 * WEB13 Semantic HTML and ARIA (WEB-4). What assistive technology is told about an element (role, accessible name,
 * state), the first rule of ARIA (a native element before a repaired div), where names come from (aria-labelledby,
 * aria-label, the element's own text/alt/label, title last), states a script must keep true (aria-pressed,
 * aria-expanded), focus management (tab order, tabindex, returning focus, Escape, hidden) and live regions (role
 * status/alert). The capstone pattern is a disclosure menu button. The site's `name` and `role` checks read a simplified
 * model of the rules and `tab`/`key` are script-made keys: the text says so and never states what a screen reader says
 * word for word. Every `observe` fact and every exercise (solution, starter, mistakes, variants) is run in Chromium by
 * the tests. Names and data are made up.
 */

