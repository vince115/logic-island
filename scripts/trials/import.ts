import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { trialBank } from '@/content/trials';
import { trialContext } from '@/content/trials/context';
import { privateFile } from '@/content/trials/private-bank';
import type { GeneratedBatch } from '@/content/trials/schema';
import { batchFileOf, importReport, planImport } from '@/lib/trials/import';
import { writeAllOrNothing } from './write-files';

/*
 * Shared Trial System T.1: import one question batch.
 *
 *   pnpm trials:import src/content/trials/batches/<batch>.json            dry-run: check and report, write nothing
 *   pnpm trials:import src/content/trials/batches/<batch>.json --write    also write the generated questions
 *   … --report docs/exam-system/imports/<batch>.md                         save the report as well
 *
 * --write puts the batch's questions in src/content/trials/generated/<batch id>.json, regenerates that folder's
 * index.ts and adds new published revisions to published-hashes.json. It writes only when every check passes and only
 * a batch at its own location (src/content/trials/batches/<batch id>.json), all three files or none (T.1.1), and the
 * same batch imported again writes the same bytes. Exit code 1 when the batch cannot be imported.
 */
const ROOT = path.resolve(fileURLToPath(new URL('../..', import.meta.url)));
const TRIALS = path.join(ROOT, 'src/content/trials');
const GENERATED = path.join(TRIALS, 'generated');
const HASHES = path.join(TRIALS, 'published-hashes.json');

const args = process.argv.slice(2);
const write = args.includes('--write');
const reportAt = args.includes('--report') ? args[args.indexOf('--report') + 1] : undefined;
const file = args.find((a, i) => !a.startsWith('--') && args[i - 1] !== '--report');
if (!file) {
  console.error('usage: pnpm trials:import <batch.json> [--write] [--report <report.md>]');
  process.exit(2);
}

let relative = path.relative(ROOT, path.resolve(file)).split(path.sep).join('/');
let raw: unknown;
try { raw = JSON.parse(readFileSync(file, 'utf8')); } catch (error) {
  console.error(`cannot read ${relative}: ${(error as Error).message}`);
  process.exit(1);
}
const batchId = (raw as { batch?: { id?: unknown } })?.batch?.id;
const validId = typeof batchId === 'string' && /^[a-z0-9-]+$/.test(batchId);
// T.3J (docs/exam-system/34): a batch in the private bank (every batch not yet published) is written there, and only
// there; the generated index of this repository lists the published batches in this folder alone.
const privateBatch = validId && typeof batchId === 'string' && path.resolve(file) === privateFile(`batches/${batchId}.json`);
if (privateBatch) relative = batchFileOf(batchId);
const outFile = validId ? path.join(privateBatch ? privateFile('generated') : GENERATED, `${batchId}.json`) : undefined;
const previous: GeneratedBatch | undefined = outFile && existsSync(outFile) ? JSON.parse(readFileSync(outFile, 'utf8')) : undefined;
const published: Record<string, string> = JSON.parse(readFileSync(HASHES, 'utf8'));

// Today on this machine (YYYY-MM-DD), only to warn about review dates that have passed.
const today = new Date().toLocaleDateString('sv-SE');
const plan = planImport(raw, trialBank, trialContext(), previous, published, relative, today);
const report = importReport(raw, plan, write ? 'write' : 'dry-run', relative);
console.log(report);
if (reportAt) writeFileSync(reportAt, report);

if (!plan.ok) process.exit(1);
if (write && outFile && plan.output && plan.hashes) {
  if (relative !== batchFileOf(plan.output.batch.id)) {
    console.error(`not written: --write takes the batch at ${batchFileOf(plan.output.batch.id)}, not ${relative}`);
    process.exit(1);
  }
  const batches = [...new Set([...readdirSync(GENERATED).filter(f => f.endsWith('.json')), ...privateBatch ? [] : [path.basename(outFile)]])].sort();
  try {
    writeAllOrNothing([
      { path: outFile, content: `${JSON.stringify(plan.output, null, 1)}\n` },
      { path: HASHES, content: `${JSON.stringify(plan.hashes, null, 1)}\n` },
      { path: path.join(GENERATED, 'index.ts'), content: [
        '// Generated by scripts/trials/import.ts from the JSON files in this folder; do not edit by hand.',
        "import type { GeneratedBatch } from '../schema';",
        "import { privateBatches } from '../private-bank';",
        ...batches.map((f, i) => `import batch${i} from './${f}';`),
        '',
        '/** The batches in this folder: published questions only (T.3J). */',
        `export const publicBatches = [${batches.map((_, i) => `batch${i}`).join(', ')}] as unknown as GeneratedBatch[];`,
        '/** With the private bank\'s batches when it is checked out, in file order (src/content/trials/private-bank.ts). */',
        'export const generatedBatches = [...publicBatches, ...privateBatches].sort((a, b) => a.batch.id < b.batch.id ? -1 : a.batch.id > b.batch.id ? 1 : 0);',
        '',
      ].join('\n') },
    ]);
  } catch (error) {
    // writeAllOrNothing has already put every original back.
    console.error(`not written (nothing was changed): ${(error as Error).message}`);
    process.exit(1);
  }
  console.error(`wrote ${privateBatch ? `${path.basename(outFile)} in the private bank` : path.relative(ROOT, outFile)}, src/content/trials/generated/index.ts and published-hashes.json`);
}
